"""Write docs/RUN_HISTORY.md: every recorded investigation in runs/ (which is gitignored), so the
history behind the demo cases (e.g. BONK's early HIGH_RISK run) is citable from the repo.

Per run: start time, agent prompt version (current or older), verdict label, LLM calls, seconds,
retries, first-round rejections, drops, and whether it is the exported demo run.

Usage: uv run python scripts/run_history.py
"""

from __future__ import annotations

import json
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from casefile.agents.prompts import AGENT_VERSION  # noqa: E402
from casefile.trace_schema import normalize, summarize  # noqa: E402

CURRENT_RULES_SINCE = "2026-10-23T12:10:00"  # same cutoff as scripts/export_demo_case.py


def main() -> int:
    rows = []
    for case_dir in sorted((ROOT / "runs").glob("m_*")):
        demo = json.loads((ROOT / "demo_cases" / case_dir.name / "meta.json").read_text()) \
            if (ROOT / "demo_cases" / case_dir.name / "meta.json").exists() else {}
        for run in sorted(p for p in case_dir.iterdir() if (p / "trace.jsonl").exists() and not p.name.startswith("_")):
            raw = [json.loads(l) for l in (run / "trace.jsonl").read_text().splitlines() if l.strip()]
            if not raw:
                continue
            ev = normalize(raw)
            c = Counter(e["type"] for e in ev)
            start = next((r["output"] for r in raw if r["step"] == "start"), {}) or {}
            version = start.get("agent_version")
            current = (version == AGENT_VERSION) if version else raw[0]["ts"] >= CURRENT_RULES_SINCE
            stats = summarize(raw)["stats"] or {}
            verdict = next((e["detail"] for e in ev if e["type"] == "verdict"), None)
            first_rejects = sum(1 for e in ev if e["type"] == "skeptic_decision"
                                and e["detail"].get("decision") == "reject" and e["detail"].get("round") == "review")
            rows.append({
                "case": case_dir.name, "symbol": start.get("symbol") or demo.get("symbol") or "?",
                "run": run.name, "started": raw[0]["ts"][:19].replace("T", " "),
                "prompts": "current" if current else "older",
                "label": verdict["label"] if verdict else "(no verdict: stopped)",
                "calls": stats.get("llm_calls", "—"), "seconds": stats.get("seconds", "—"),
                "retries": c["retry"], "rejected": first_rejects, "dropped": c["claim_dropped"],
                "demo": "yes" if demo.get("run_id") == run.name else "",
            })
    rows.sort(key=lambda r: (r["symbol"], r["started"]))
    lines = [
        "# Run history",
        "",
        "Every investigation recorded under `runs/` (gitignored), generated by `scripts/run_history.py`.",
        "\"prompts\" is `current` when the run used today's agent prompts and rules (recorded",
        "`agent_version`, or for older runs a start after the final verdict/Skeptic rule change at",
        f"{CURRENT_RULES_SINCE} UTC). \"demo\" marks the run exported to `demo_cases/`.",
        "\"rejected\" counts first-round Skeptic rejections; each one sends the claim back once.",
        "",
        "| Token | Run | Started (UTC) | Prompts | Verdict | LLM calls | Seconds | Retries | Rejected | Dropped | Demo |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        lines.append(f"| {r['symbol']} | `{r['run']}` | {r['started']} | {r['prompts']} | {r['label']} | {r['calls']} | "
                     f"{r['seconds']} | {r['retries']} | {r['rejected']} | {r['dropped']} | {r['demo']} |")
    lines.append("")
    (ROOT / "docs" / "RUN_HISTORY.md").write_text("\n".join(lines))
    print(f"wrote docs/RUN_HISTORY.md: {len(rows)} runs")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
